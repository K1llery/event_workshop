local passed = 0
local function test(name, fn) fn(); passed = passed + 1; print("通过：扩展 / " .. name) end
local function rule(event, kind, params)
    params = params or {}; params.kind = kind
    return { enabled = true, event = event, actions = { params } }
end
local function setup(rules)
    G.entities, G.spawned, G.logs, G.curses, G.grids, G.doors = {}, {}, {}, 0, nil, nil
    G.clear, G.watch, G.paused, G.players = true, 0, false, { G.newPlayer(0) }
    local config = S.default(); config.profiles[1].rules = {}
    for index, raw in ipairs(rules) do config.profiles[1].rules[index] = S.rule(raw, index) end
    config.nextRuleId = #rules + 1
    G.stored = G.json.encode({ config = config })
    G.reload(); G.start(); G.command("on"); G.tick()
    return G.players[1]
end
local function ticks(n) for _ = 1, n or 6 do G.tick() end end
local function counters()
    G.fire(ModCallbacks.MC_PRE_GAME_EXIT, true)
    return G.saved().run.counters
end
local function menu(tab, prefix)
    for _, row in ipairs(G.rows[tab] or {}) do
        local label = type(row.Display) == "function" and row.Display() or row.Display
        if label and label:sub(1, #prefix) == prefix then return row end
    end
    error("缺少菜单项: " .. prefix)
end

